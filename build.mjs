// Builds every plugin under plugins/ into the distribution layout:
//   dist/pool/<path>@<version>.zip        the installable artifact for a version
//   dist/<path>/{index.js,manifest.json}  the folder URL a user pastes into Revenge
//   dist/<path>/index.json                a one-plugin repository index — GitHub
//                                         Pages serves index.json for a directory
//                                         URL, which is what makes that link
//                                         answer with JSON instead of the 404
//                                         page (an install reporting "failed to
//                                         manifest" is exactly that difference)
//   dist/{index.js,manifest.json}         root install for the published plugin
//   dist/index.json                       repository index for Revenge's browser
//
// <path> is a plugin's id when publish.json advertises it, and the opaque slug
// from publish.json when it does not, so no path the site serves spells out an
// unlisted plugin's name. dist/ is wiped first: it *is* the published surface,
// and a file left over from an earlier layout keeps being served otherwise —
// which is how /dev.8uvu.fake-dm/ stayed reachable after that plugin was unlisted.
//
// Follows the revenge-plugin-template conventions:
//   - manifest.json (format 1) declares id, version, dependencies, dist.script
//   - the JS entry is looked up in js/index.*, then src/index.*, then the
//     plugin folder itself (ts/tsx/js/jsx), and bundled with esbuild
//   - bare requires of react/react-native/clipboard/@revenge-mod/* are
//     rewritten to `revenge.*` lookups (current plugins resolve everything
//     lazily and import nothing, so this is a safety net for future ones)
//   - the bundle is wrapped as the single expression the host evaluates:
//     (() => { CJS shim; ...; return (module.exports&&module.exports.default)||module.exports })()
import { readFile, writeFile, copyFile, mkdir, readdir, rm } from "fs/promises";
import { existsSync } from "node:fs";
import { createHash } from "node:crypto";
import { createRequire } from "node:module";
import { zipSync, strToU8 } from "fflate";
import esbuild from "esbuild";

const require = createRequire(import.meta.url);
const {
    BASE_URL,
    installUrl,
    readPolicy,
    requireInstallPath,
    zipName,
} = require("./scripts/publish-paths.cjs");

// publish.json is the whole publishing policy: which plugin ids appear in
// dist/index.json (the list Revenge's plugin browser shows, and the only place
// the site names a plugin), which plugin the bare repository URL installs, and
// the opaque path each unlisted plugin is published under. Everything else still
// builds and stays installable by its own folder URL — it is simply published at
// a slug, advertised nowhere, and named in no path or file the site serves.
// scripts/check-dist.cjs fails the build if any of that stops being true.
const policy = readPolicy();
const ROOT_PLUGIN_ID = policy.root;
const PUBLISHED_PLUGIN_IDS = policy.published;

// dist/ is the published surface, not a build cache: wipe it so a plugin that was
// renamed or unlisted cannot keep serving at a path an earlier build created.
await rm("./dist", { recursive: true, force: true });

// The site's 404 page. Deliberately says nothing about any plugin: a directory
// URL (…/dev.8uvu.message-logger/) lands here, and it used to be generated by
// appending the whole README — which listed every plugin in the repository.
const NOT_FOUND_PAGE = `---
permalink: /404.html
---

# Nothing here

This link did not resolve to a plugin. Copy the install URL exactly as you got
it — including the trailing slash — and paste it into Revenge's plugin box.
`;

// fflate stamps every entry with the current *local* time, so the same source
// produced a different archive — and therefore a different sha256 in
// index.json — on every build, on every machine, in every timezone. That made
// the hash unverifiable and let a published artifact diverge from the one that
// was tested without anyone noticing, so pin the DOS timestamp fields here.
//
// The archive's own structure is walked (end-of-central-directory record, then
// each central directory entry and the local header it points at) instead of
// scanning for signatures: compressed data may contain any byte sequence.
const DOS_TIME = 0; // 00:00:00
const DOS_DATE = (1 << 5) | 1; // 1980-01-01 (year 0, month 1, day 1)

function reproducibleZip(entries) {
    const bytes = Uint8Array.from(zipSync(entries));
    const view = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);

    let eocd = -1;
    for (let i = bytes.length - 22; i >= 0; i--) {
        if (view.getUint32(i, true) === 0x06054b50) {
            eocd = i;
            break;
        }
    }
    if (eocd < 0) throw new Error("zip: no end-of-central-directory record");

    const entriesCount = view.getUint16(eocd + 10, true);
    let cd = view.getUint32(eocd + 16, true);
    for (let i = 0; i < entriesCount; i++) {
        if (view.getUint32(cd, true) !== 0x02014b50) throw new Error("zip: bad central directory entry");
        view.setUint16(cd + 12, DOS_TIME, true);
        view.setUint16(cd + 14, DOS_DATE, true);
        const local = view.getUint32(cd + 42, true);
        if (view.getUint32(local, true) !== 0x04034b50) throw new Error("zip: bad local file header");
        view.setUint16(local + 10, DOS_TIME, true);
        view.setUint16(local + 12, DOS_DATE, true);
        cd += 46 + view.getUint16(cd + 28, true) + view.getUint16(cd + 30, true) + view.getUint16(cd + 32, true);
    }
    return Buffer.from(bytes);
}

const artifacts = [];
const plugins = [];

for (let plug of await readdir("./plugins", { withFileTypes: true })) {
    if (!plug.isDirectory()) continue;
    const name = plug.name;
    const dir = `./plugins/${name}`;

    const manifest = JSON.parse(
        (await readFile(`${dir}/manifest.json`, "utf8")).replace(/^\uFEFF/, ""),
    );
    const id = manifest.id ?? name;
    const version = manifest.version;
    if (!id || !version) throw new Error(`${name}: missing id or version`);

    // The path this plugin is published at: its id when publish.json advertises
    // it, its opaque slug otherwise. requireInstallPath throws rather than ever
    // handing back the real id for an unlisted plugin.
    const path = requireInstallPath(id, policy);

    const script = (manifest.dist && manifest.dist.script) || manifest.main || "index.js";

    // Template entry lookup: js/index.*, then src/index.*, then folder root.
    let entry = null;
    outer: for (const base of [`${dir}/js`, `${dir}/src`, dir]) {
        for (const ext of ["ts", "tsx", "js", "jsx"]) {
            const p = `${base}/index.${ext}`;
            if (existsSync(p)) {
                entry = p;
                break outer;
            }
        }
    }
    if (!entry) throw new Error(`${name}: no index.{ts,tsx,js,jsx} entry found`);

    const result = await esbuild.build({
        entryPoints: [entry],
        bundle: true,
        format: "cjs",
        platform: "neutral",
        target: "es2019",
        minify: false,
        define: { __DEV__: "false", IS_DEV: "false" },
        external: ["@revenge-mod/*", "@react-native-clipboard/clipboard"],
        write: false,
    });
    let bundle = result.outputFiles[0].text;

    const map = {
        "react": "({ default: revenge.react.React, ...revenge.react.React })",
        "react/jsx-runtime": "({ jsx: (revenge.react.jsxRuntime || revenge.react.ReactJSXRuntime).jsx, jsxs: (revenge.react.jsxRuntime || revenge.react.ReactJSXRuntime).jsxs, Fragment: (revenge.react.jsxRuntime || revenge.react.ReactJSXRuntime).Fragment })",
        "react-native": "({ ...revenge.react.ReactNative })",
        "@react-native-clipboard/clipboard": "({ default: revenge.externals.ReactNativeClipboard.Clipboard, ...revenge.externals.ReactNativeClipboard.Clipboard })",
        "@revenge-mod/discord/flux": "revenge.discord.flux",
        "@revenge-mod/discord/design": "revenge.discord.design",
        "@revenge-mod/discord/native": "revenge.discord.native",
        "@revenge-mod/discord/actions": "revenge.discord.actions",
    };
    for (const [pkg, expr] of Object.entries(map)) {
        bundle = bundle.split(`require("${pkg}")`).join(`(${expr})`);
    }
    const leftover = [...bundle.matchAll(/require\("([^"]+)"\)/g)].map((m) => m[1]);
    if (leftover.length) {
        console.error(`${id}: UNMAPPED REQUIRES: ${[...new Set(leftover)].join(", ")}`);
        process.exit(1);
    }

    const wrapped = `(() => { const module = { exports: {} }; const exports = module.exports; ${bundle}; return (module.exports && module.exports.default) || module.exports; })()`;
    const bundleBytes = Buffer.from(wrapped, "utf8");
    const bundleHash = createHash("sha256").update(bundleBytes).digest("hex");

    // Hybrid manifest: `main`/`hash`/`authors`/`vendetta` keep the direct
    // folder-URL install working on vendetta-style clients, while the new
    // format fields wire up jsonStorage/settings on current Revenge builds.
    const deployed = {
        ...manifest,
        main: script,
        hash: bundleHash,
        authors: [{ name: manifest.author ?? "Unknown" }],
        vendetta: { icon: "ic_chat_bubble" },
    };

    const artifactName = zipName(id, version, policy);
    const zip = reproducibleZip({
        "manifest.json": strToU8(JSON.stringify(manifest, null, 4)),
        [script]: bundleBytes,
    });

    await mkdir("./dist/pool", { recursive: true });
    await writeFile(`./dist/pool/${artifactName}`, Buffer.from(zip));

    const entryObj = {
        url: `${BASE_URL}/pool/${artifactName}`,
        sha256: createHash("sha256").update(zip).digest("hex"),
        size: zip.length,
        dependencies: Object.fromEntries(
            Object.entries(manifest.dependencies ?? {}).map(([depId, dep]) => [
                depId,
                { version: dep.version, optional: dep.optional },
            ]),
        ),
    };

    artifacts.push(artifactName);
    plugins.push({ id, version, manifest, entry: entryObj });

    await mkdir(`./dist/${path}`, { recursive: true });
    await writeFile(`./dist/${path}/index.js`, bundleBytes);
    await writeFile(`./dist/${path}/manifest.json`, JSON.stringify(deployed, null, 4));

    console.log(`Packaged ${id}@${version} (${zip.length} bytes) -> pool/${artifactName} (published at /${path}/)`);
}

// The shape Revenge reads for one plugin: the same entry whether it appears in
// the repository index or in the one-plugin index.json inside a plugin folder.
function pluginEntry(id, manifest) {
    let latest = null;
    for (const p of plugins) {
        if (p.id !== id) continue;
        if (!/-/.test(p.version) && (latest === null || p.version > latest)) latest = p.version;
    }
    return {
        name: manifest.name,
        description: manifest.description ?? "",
        author: manifest.author ?? "",
        channels: { ...(latest ? { latest } : {}) },
        versions: Object.fromEntries(
            plugins.filter((p) => p.id === id).map((p) => [p.version, p.entry]),
        ),
    };
}

// Second pass: every plugin folder gets its own one-plugin repository index, so
// /<path>/ answers with a valid repository while /<path>/manifest.json answers
// with the manifest — whichever of them the install box fetches, it gets JSON.
for (const { id, manifest } of plugins) {
    const path = requireInstallPath(id, policy);
    const folderIndex = {
        format: 1,
        name: manifest.name,
        description: manifest.description ?? "Revenge plugins by 8uvu",
        plugins: { [id]: pluginEntry(id, manifest) },
    };
    await writeFile(`./dist/${path}/index.json`, JSON.stringify(folderIndex, null, 4) + "\n");
}

// Root-level plugin install: pasting https://8uvu.github.io/msglog/ straight
// into Revenge's plugin URL box fetches <root>/manifest.json then <root>/index.js.
const primary = plugins.find((p) => p.id === ROOT_PLUGIN_ID) ?? plugins[0];
if (primary) {
    const { id, manifest } = primary;
    const script = (manifest.dist && manifest.dist.script) || manifest.main || "index.js";
    const primaryPath = requireInstallPath(id, policy);
    const bundleBytes = await readFile(`./dist/${primaryPath}/index.js`);
    const rootDeployed = {
        ...manifest,
        main: script,
        hash: createHash("sha256").update(bundleBytes).digest("hex"),
        authors: [{ name: manifest.author ?? "Unknown" }],
        vendetta: { icon: "ic_chat_bubble" },
    };
    await copyFile(`./dist/${primaryPath}/index.js`, `./dist/index.js`);
    await writeFile(`./dist/manifest.json`, JSON.stringify(rootDeployed, null, 4));
    console.log(`Root plugin install: ${id} (index.js + manifest.json)`);
}

const output = {};
const unlisted = [];
for (const { id, manifest } of plugins) {
    if (!PUBLISHED_PLUGIN_IDS.includes(id)) {
        unlisted.push(id);
        continue;
    }
    output[id] = pluginEntry(id, manifest);
}

const index = {
    format: 1,
    name: "msglog",
    description: "Revenge plugins by 8uvu",
    plugins: output,
};

await writeFile("./dist/index.json", JSON.stringify(index, null, 4) + "\n");
await writeFile("./dist/404.md", NOT_FOUND_PAGE);
if (unlisted.length) {
    console.log(
        `Unlisted (absent from index.json, published only at their opaque path): ${unlisted
            .map((id) => `${id} -> /${requireInstallPath(id, policy)}/`)
            .join(", ")}`,
    );
}
console.log(
    `Wrote index.json: ${Object.keys(output).length} published plugin(s), ${artifacts.length} artifact(s)`,
);

// Printed so nobody has to derive an install URL by hand: an unlisted plugin's
// URL is an opaque path that only publish.json knows.
console.log("\nInstall URLs (paste into Revenge):");
for (const { id, version } of plugins) {
    console.log(`  ${PUBLISHED_PLUGIN_IDS.includes(id) ? "listed  " : "unlisted"}  ${installUrl(id, policy)}  (${id} @ ${version})`);
}
